"""
Requirement → test → evidence traceability check (audit F-12).

    .venv/Scripts/python.exe scripts/trace_check.py [--strict]

Reads configs/traceability.yaml, checks that every referenced test file and
test function exists and every evidence file exists, and that every REQ ID
found in the requirement documents is mapped.  Writes reports/traceability.md.
--strict exits non-zero on missing tests/evidence or unmapped requirements.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
REQ_DOCS = [
    ROOT / "W100000" / "requirements.md",
    ROOT / "design_md" / "W200000" / "W2_requirements.md",
    ROOT / "design_md" / "W300000" / "W3_requirements.md",
    ROOT / "design_md" / "W400000" / "W4_requirements.md",
]


def documented_reqs():
    ids = set()
    for p in REQ_DOCS:
        if p.exists():
            ids |= set(re.findall(r"^## (REQ-[W0-9]+)", p.read_text(encoding="utf-8"), flags=re.M))
    return ids


def test_exists(ref: str) -> bool:
    path, _, name = ref.partition("::")
    f = ROOT / path
    if not f.exists():
        return False
    if not name:
        return True
    return re.search(rf"^\s*def {re.escape(name)}\(", f.read_text(encoding="utf-8"), flags=re.M) is not None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--strict", action="store_true")
    a = ap.parse_args()
    reqs = yaml.safe_load((ROOT / "configs" / "traceability.yaml").read_text(encoding="utf-8"))["requirements"]
    rows, problems = [], []
    for rid, r in reqs.items():
        missing_t = [t for t in r.get("tests", []) if not test_exists(t)]
        missing_e = [e for e in r.get("evidence", []) if not (ROOT / e).exists()]
        status = r.get("status", "")
        if missing_t or missing_e:
            state = "MISSING"
            problems.append(f"{rid}: missing tests {missing_t} evidence {missing_e}")
        elif status.startswith("blocked"):
            state = "blocked"
        elif status.startswith("not_met"):
            state = "acceptance not met"
        elif status.startswith("inconclusive"):
            state = "inconclusive"                     # design 6.2: too few sessions to judge
        else:
            state = "verified"
        rows.append((rid, r.get("title", ""), len(r.get("tests", [])), len(r.get("evidence", [])), state,
                     status.split(":", 1)[1].strip() if ":" in status else ""))
    unmapped = sorted(documented_reqs() - set(reqs))
    for u in unmapped:
        problems.append(f"{u}: documented but not mapped")
    lines = ["# Requirement traceability", "", "Generated by `scripts/trace_check.py` from `configs/traceability.yaml`.", "",
             "| REQ | Title | Tests | Evidence | State | Note |", "| --- | --- | --- | --- | --- | --- |"]
    lines += [f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} |" for r in rows]
    counts = {s: sum(1 for r in rows if r[4] == s) for s in ("verified", "blocked", "acceptance not met", "inconclusive", "MISSING")}
    lines += ["", "Summary: " + ", ".join(f"{k} {v}" for k, v in counts.items())
              + (f"; unmapped: {', '.join(unmapped)}" if unmapped else "")]
    out = ROOT / "reports" / "traceability.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    sys.stdout.buffer.write(("\n".join(lines[-1:] + problems) + "\n").encode("utf-8"))
    return 1 if (a.strict and problems) else 0


if __name__ == "__main__":
    sys.exit(main())
